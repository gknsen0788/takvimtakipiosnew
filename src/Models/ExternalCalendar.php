<?php
declare(strict_types=1);

namespace App\Models;

use App\Database;
use App\Helpers;
use App\IcalEngine;
use PDO;

class ExternalCalendar {
    public static function create(array $data, int $userId): bool {
        $db = Database::getConnection();

        // Check ownership
        $villa = Villa::find((int)$data['villa_id'], $userId, \App\Auth::isAdmin());
        if (!$villa) return false;

        $stmt = $db->prepare("
            INSERT INTO external_calendars (villa_id, name, ical_url, source_type, sync_status)
            VALUES (:villa_id, :name, :url, :source_type, 'pending')
        ");
        $success = $stmt->execute([
            'villa_id' => $data['villa_id'],
            'name' => $data['name'],
            'url' => $data['ical_url'],
            'source_type' => $data['source_type'] ?? 'generic_ical'
        ]);

        if ($success) {
            $id = (int)$db->lastInsertId();
            Helpers::auditLog($userId, 'EXTERNAL_CALENDAR_CREATED', 'external_calendars', $id);
            // Trigger immediate initial sync
            $cal = self::find($id);
            if ($cal) {
                IcalEngine::syncExternalCalendar($cal);
            }
        }

        return $success;
    }

    public static function delete(int $id, int $userId): bool {
        $db = Database::getConnection();
        $cal = self::find($id);
        if (!$cal) return false;

        $villa = Villa::find((int)$cal['villa_id'], $userId, \App\Auth::isAdmin());
        if (!$villa) return false;

        // Decouple reservations generated by this calendar so they are preserved in the calendar
        $db->prepare("UPDATE reservations SET external_calendar_id = NULL WHERE external_calendar_id = :id")->execute(['id' => $id]);

        $stmt = $db->prepare("DELETE FROM external_calendars WHERE id = :id");
        $success = $stmt->execute(['id' => $id]);

        if ($success) {
            Helpers::auditLog($userId, 'EXTERNAL_CALENDAR_DELETED', 'external_calendars', $id);
        }

        return $success;
    }

    public static function find(int $id): ?array {
        $db = Database::getConnection();
        $stmt = $db->prepare("SELECT * FROM external_calendars WHERE id = :id");
        $stmt->execute(['id' => $id]);
        return $stmt->fetch() ?: null;
    }

    public static function getByVilla(int $villaId): array {
        $db = Database::getConnection();
        $stmt = $db->prepare("SELECT * FROM external_calendars WHERE villa_id = :villa_id ORDER BY created_at DESC");
        $stmt->execute(['villa_id' => $villaId]);
        return $stmt->fetchAll();
    }

    public static function syncAll(): void {
        $db = Database::getConnection();
        $stmt = $db->prepare("SELECT * FROM external_calendars");
        $stmt->execute();
        $calendars = $stmt->fetchAll();
        foreach ($calendars as $cal) {
            IcalEngine::syncExternalCalendar($cal);
        }
    }
}
